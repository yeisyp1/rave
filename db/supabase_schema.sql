-- solo se marca 'Realizado' si el ultimo consentimiento del plan fue aceptado.
create or replace function public.check_patient_procedure_plan()
returns trigger language plpgsql set search_path = '' as $$
declare
  v_plan public.treatment_plans;
  v_accepted boolean;
begin
  if new.treatment_plan_id is null then
    return new;
  end if;

  select * into v_plan from public.treatment_plans where id = new.treatment_plan_id;
  if v_plan.patient_id <> new.patient_id then
    raise exception 'El plan de tratamiento pertenece a otro paciente.';
  end if;
  if tg_op = 'INSERT' and v_plan.status <> 'Abierto' then
    raise exception 'El plan de tratamiento está %: no se le pueden agregar tratamientos.', lower(v_plan.status);
  end if;

  if new.status = 'Realizado' and (tg_op = 'INSERT' or old.status is distinct from 'Realizado') then
    select c.aceptado into v_accepted
    from public.informed_consents c
    where c.treatment_plan_id = new.treatment_plan_id
    order by c.signed_at desc, c.id desc
    limit 1;
    if v_accepted is null then
      raise exception 'El plan no tiene consentimiento informado: regístralo antes de marcar tratamientos como realizados.';
    elsif not v_accepted then
      raise exception 'El paciente no aceptó el consentimiento de este plan: el tratamiento no se puede realizar.';
    end if;
  end if;

  return new;
end;
$$;
