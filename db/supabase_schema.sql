create or replace function public.deduct_inventory_stock(p_item_id bigint, p_quantity numeric)
returns void language plpgsql set search_path = '' as $$
declare
  v_item public.inventory_items;
begin
  select * into v_item from public.inventory_items where id = p_item_id for update;
  if v_item.stock < p_quantity then
    raise exception 'Stock insuficiente de "%": hay % %, el tratamiento requiere %.',
      v_item.name, v_item.stock, v_item.unit, p_quantity;
  end if;
  update public.inventory_items set stock = stock - p_quantity where id = p_item_id;
end;
$$;

create or replace function public.apply_procedure_inventory()
returns trigger language plpgsql set search_path = '' as $$
declare
  r record;
begin
  if new.status = 'Realizado' and old.status is distinct from 'Realizado' then
    for r in
      select id, inventory_item_id, quantity from public.treatment_inventory_items
      where patient_procedure_id = new.id and deducted_at is null
    loop
      perform public.deduct_inventory_stock(r.inventory_item_id, r.quantity);
      update public.treatment_inventory_items set deducted_at = now() where id = r.id;
    end loop;
  elsif old.status = 'Realizado' and new.status <> 'Realizado' then
    update public.inventory_items i set stock = i.stock + t.quantity
    from public.treatment_inventory_items t
    where t.patient_procedure_id = new.id and t.deducted_at is not null and i.id = t.inventory_item_id;
    update public.treatment_inventory_items set deducted_at = null
    where patient_procedure_id = new.id and deducted_at is not null;
  end if;
  return new;
end;
$$;
create trigger trg_patient_procedures_inventory after update of status on public.patient_procedures
  for each row execute function public.apply_procedure_inventory();

