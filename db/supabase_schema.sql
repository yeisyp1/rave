-- Estado de la factura y reglas de anulacion.
create or replace function public.billing_invoice_status()
returns trigger language plpgsql set search_path = '' as $$
declare
  v_paid numeric;
begin
  if tg_op = 'UPDATE' and old.status = 'Anulado' then
    if new.status <> 'Anulado' then
      raise exception 'Una factura anulada no se puede reactivar.';
    end if;
    return new;
  end if;

  select coalesce(sum(amount), 0) into v_paid
  from public.payments where invoice_id = new.id and not anulado;

  if new.status = 'Anulado' then
    if coalesce(trim(new.motivo_anulacion), '') = '' then
      raise exception 'Indica el motivo de anulación de la factura.';
    end if;
    if v_paid > 0 then
      raise exception 'La factura tiene pagos registrados: anúlalos antes de anular la factura.';
    end if;
    new.anulada_at := now();
    new.anulada_por := coalesce(new.anulada_por, auth.uid());
    return new;
  end if;

  if new.amount < v_paid then
    raise exception 'El monto de la factura no puede ser menor a lo ya pagado ($%).', v_paid;
  end if;
  new.status := case
    when v_paid > 0 and v_paid >= new.amount then 'Pagado'
    when v_paid > 0 then 'Parcial'
    else 'Pendiente'
  end;
  return new;
end;
$$;
create trigger trg_billing_invoices_status before insert or update on public.billing_invoices
  for each row execute function public.billing_invoice_status();

create or replace function public.check_payment()
returns trigger language plpgsql set search_path = '' as $$
declare
  v_invoice public.billing_invoices;
  v_paid numeric;
begin
  if tg_op = 'INSERT' then
    select * into v_invoice from public.billing_invoices where id = new.invoice_id for update;
    if v_invoice.status = 'Anulado' then
      raise exception 'No se pueden registrar pagos en una factura anulada.';
    end if;
    select coalesce(sum(amount), 0) into v_paid
    from public.payments where invoice_id = new.invoice_id and not anulado;
    if new.amount > v_invoice.amount - v_paid then
      raise exception 'El pago ($%) supera el saldo pendiente ($%).', new.amount, v_invoice.amount - v_paid;
    end if;
    new.anulado := false;
    new.motivo_anulacion := null;
    new.anulado_por := null;
    new.anulado_at := null;
    return new;
  end if;

  if old.anulado then
    raise exception 'Un pago anulado no se puede modificar.';
  end if;
  if not new.anulado
     or (new.invoice_id, new.amount, new.paid_at, new.method, new.reference, new.notes, new.registered_by)
        is distinct from (old.invoice_id, old.amount, old.paid_at, old.method, old.reference, old.notes, old.registered_by) then
    raise exception 'Los pagos no se editan: anula el pago con un motivo y registra uno nuevo.';
  end if;
  if coalesce(trim(new.motivo_anulacion), '') = '' then
    raise exception 'Indica el motivo de anulación del pago.';
  end if;
  new.anulado_at := now();
  new.anulado_por := coalesce(new.anulado_por, auth.uid());
  return new;
end;
$$;
create trigger trg_payments_check before insert or update on public.payments
  for each row execute function public.check_payment();

-- Cada pago (o su anulacion) recalcula el estado de su factura via trg_billing_invoices_status.
create or replace function public.refresh_invoice_after_payment()
returns trigger language plpgsql set search_path = '' as $$
begin
  update public.billing_invoices set status = status
  where id = new.invoice_id and status <> 'Anulado';
  return null;
end;
$$;
create trigger trg_payments_refresh_invoice after insert or update on public.payments
  for each row execute function public.refresh_invoice_after_payment();

-- Crear la factura y sus items en una sola transaccion; el monto es la suma de los items.
create or replace function public.create_invoice_with_items(p_invoice jsonb, p_items jsonb)
returns public.billing_invoices language plpgsql set search_path = '' as $$
declare
  v_invoice public.billing_invoices;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'La factura debe tener al menos un concepto.';
  end if;

  insert into public.billing_invoices (patient_id, patient_document, patient_name, date, amount, metadata)
  values (
    nullif(p_invoice->>'patient_id', '')::uuid,
    p_invoice->>'patient_document',
    p_invoice->>'patient_name',
    (p_invoice->>'date')::date,
    0,
    p_invoice->'metadata'
  )
  returning * into v_invoice;

  insert into public.invoice_items (invoice_id, patient_procedure_id, description, quantity, unit_price)
  select v_invoice.id,
         nullif(item->>'patient_procedure_id', '')::bigint,
         item->>'description',
         coalesce((item->>'quantity')::numeric, 1),
         coalesce((item->>'unit_price')::numeric, 0)
  from jsonb_array_elements(p_items) as item;

  update public.billing_invoices
  set amount = (select coalesce(sum(total), 0) from public.invoice_items where invoice_id = v_invoice.id)
  where id = v_invoice.id
  returning * into v_invoice;

  return v_invoice;
end;
$$;
revoke execute on function public.create_invoice_with_items(jsonb, jsonb) from public, anon;
grant execute on function public.create_invoice_with_items(jsonb, jsonb) to authenticated;

